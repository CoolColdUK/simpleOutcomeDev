export function AdminIconButton({
  label,
  icon,
  disabled,
  expanded,
  onClick,
}: {
  label: string;
  icon: 'bin' | 'settings';
  disabled?: boolean;
  expanded?: boolean;
  onClick: () => void;
}) {
  const danger = icon === 'bin';
  return (
    <button
      type="button"
      className={danger ? 'admin-icon-button danger' : 'admin-icon-button'}
      aria-label={label}
      title={label}
      disabled={disabled}
      {...(expanded === undefined ? {} : {'aria-expanded': expanded})}
      onClick={onClick}
    >
      {danger ? <AdminDeleteIcon /> : <AdminSettingsIcon />}
    </button>
  );
}
